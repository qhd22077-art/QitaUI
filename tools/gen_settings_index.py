#!/usr/bin/env python3
"""Writes SettingsIndex.kt: every labelled row of the Settings pages with the page it is on, for the Settings search.

Run from the repository root after adding, renaming or moving a settings row:
    python3 tools/gen_settings_index.py
"""
import re, sys

SRC = "app/src/main/java/com/qita/ui/ui/SettingsPage.kt"
OUT = "app/src/main/java/com/qita/ui/ui/SettingsIndex.kt"

text = open(SRC, encoding="utf-8").read()
start = text.index("when (current) {")
body = text[start:]
page_re = re.compile(r'^ {24}"(\w+)" -> \{', re.M)
row_re = re.compile(r'\b(?:MenuRow|CheckRow|ChoiceRow|SliderRow|SwatchRow)\(\s*"[^"]*"\s*,\s*"[^"]*"\s*,\s*"((?:[^"\\]|\\.)*)"')
pages = [(m.start(), m.group(1)) for m in page_re.finditer(body)]
seen = set()
entries = []
for r in row_re.finditer(body):
    owner = [p for pos, p in pages if pos < r.start()]
    if not owner:
        continue
    label = r.group(1)
    if "$" in label or not label.strip():
        continue
    key = (owner[-1], label)
    if key not in seen:
        seen.add(key)
        entries.append(key)

with open(OUT, "w", encoding="utf-8") as f:
    f.write("package com.qita.ui.ui\n\n")
    f.write("// Generated by tools/gen_settings_index.py from SettingsPage.kt. Do not edit by hand: run the script again after changing a settings row.\n\n")
    f.write("/** One row of the Settings pages: the page it is on (as in the tab list) and its label. */\n")
    f.write("class SettingsEntry(val page: String, val label: String)\n\n")
    f.write("val SETTINGS_INDEX: List<SettingsEntry> = listOf(\n")
    for page, label in entries:
        f.write(f'    SettingsEntry("{page}", "{label}"),\n')
    f.write(")\n")
print(len(entries), "rows", file=sys.stderr)
